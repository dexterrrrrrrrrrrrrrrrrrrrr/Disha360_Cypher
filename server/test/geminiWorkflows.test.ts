import request from 'supertest';
import { ApiError } from '@google/genai';
import { testDatabase, studentAccount, studentCall } from './helpers/student.js';
import { geminiResponse, geminiSetup, geminiAnswer, geminiFeedback, geminiSuggestion } from './helpers/gemini.js';
import { resumeFixture } from './helpers/resume.js';
import { createApp } from '../src/app.js';
import { GeminiAIService } from '../src/services/geminiAI.js';
import { InterviewSession } from '../src/models/InterviewSession.js';
import { InterviewFeedback } from '../src/models/InterviewFeedback.js';
import { Resume } from '../src/models/Resume.js';
import { ResumeAnalysis } from '../src/models/ResumeAnalysis.js';
import { analyzeResume } from '../src/services/resumeAnalysis.js';
let db: Awaited<ReturnType<typeof testDatabase>>;
beforeAll(async () => { db = await testDatabase(); }, 180000);
beforeEach(async () => db.clear());
afterAll(async () => db?.close());
function configured() {
  const generateContent = vi.fn().mockResolvedValue(geminiResponse({ question: 'Explain how you built and tested your React component.' }));
  const provider = new GeminiAIService({ primaryKey: 'fixture-primary', backupKey: 'fixture-backup', model: 'gemini-test' }, () => ({ generateContent }));
  const app = createApp({ clientOrigin: 'http://localhost:5173', databaseConfigured: true, interviewProvider: provider });
  return { app, generateContent };
}
it.each(['technical', 'hr'] as const)('generates %s questions, answer-based follow-ups, feedback and private history through Gemini', async type => {
  const { app, generateContent } = configured(); const s = await studentAccount();
  const config = await studentCall(app, s.cookie, 'get', '/interviews/config');
  expect(config.body.data).toMatchObject({ configured: true, provider: 'Google Gemini', resumeSuggestionsAvailable: true });
  expect(JSON.stringify(config.body)).not.toMatch(/fixture-primary|fixture-backup|keySelection/);
  const start = await studentCall(app, s.cookie, 'post', '/interviews', { ...geminiSetup, type });
  expect(start.status).toBe(201); const id = start.body.data.session.id;
  expect(JSON.parse(generateContent.mock.calls[0][0].contents).setup).toMatchObject({ type, targetRole: geminiSetup.targetRole, focus: geminiSetup.focus, difficulty: geminiSetup.difficulty });
  generateContent.mockResolvedValueOnce(geminiResponse({ question: 'What did your fallback test assert about the error boundary?' }));
  const answered = await studentCall(app, s.cookie, 'post', `/interviews/${id}/answers`, { answer: geminiAnswer, version: 1 });
  expect(answered.status).toBe(200); expect(answered.body.data.session.messages[2].text).toContain('fallback');
  expect(generateContent.mock.calls[1][0].contents).toContain(geminiAnswer);
  expect((await studentCall(app, s.cookie, 'post', `/interviews/${id}/complete`, { version: 2 })).status).toBe(200);
  generateContent.mockResolvedValueOnce(geminiResponse(geminiFeedback()));
  const feedback = await studentCall(app, s.cookie, 'post', `/interviews/${id}/feedback`, {});
  expect(feedback.status).toBe(200); expect(feedback.body.data.report).toMatchObject({ provider: 'Google Gemini', overallScore: 70, answeredCount: 1 });
  expect(feedback.body.data.report.disclaimer).toContain('AI-generated');
  expect(generateContent.mock.calls[2][0].contents).toContain(geminiAnswer);
  const other = await studentAccount(); const trainer = await studentAccount('trainer');
  expect((await studentCall(app, other.cookie, 'get', `/interviews/${id}`)).status).toBe(404);
  expect((await studentCall(app, other.cookie, 'post', `/interviews/${id}/feedback`, {})).status).toBe(404);
  expect((await studentCall(app, trainer.cookie, 'get', `/interviews/${id}/feedback`)).status).toBe(403);
  expect((await studentCall(app, s.cookie, 'get', '/interviews')).body.data.sessions).toHaveLength(1);
  expect((await studentCall(app, other.cookie, 'get', '/interviews')).body.data.sessions).toEqual([]);
  expect(await InterviewFeedback.countDocuments()).toBe(1);
});
it('preserves saved answers and history after Gemini quota failure, without fabricated questions or feedback', async () => {
  const { app, generateContent } = configured(); const s = await studentAccount();
  generateContent.mockRejectedValueOnce(new ApiError({ status: 429, message: 'PRIVATE provider details' }));
  const fail = await studentCall(app, s.cookie, 'post', '/interviews', geminiSetup);
  expect(fail.status).toBe(503); expect(fail.body.error.code).toBe('AI_LIMITED'); expect(JSON.stringify(fail.body)).not.toContain('PRIVATE');
  expect(await InterviewSession.countDocuments()).toBe(0);
  const start = await studentCall(app, s.cookie, 'post', '/interviews', geminiSetup); const id = start.body.data.session.id;
  generateContent.mockRejectedValueOnce(new ApiError({ status: 429, message: 'fixture quota exhausted' }));
  expect((await studentCall(app, s.cookie, 'post', `/interviews/${id}/answers`, { answer: geminiAnswer, version: 1 })).status).toBe(503);
  const unchanged = await InterviewSession.findById(id);
  expect(unchanged?.messages).toHaveLength(1); expect(unchanged?.version).toBe(1); expect(unchanged?.leaseToken).toBeUndefined();
  await studentCall(app, s.cookie, 'post', `/interviews/${id}/answers`, { answer: geminiAnswer, version: 1 });
  await studentCall(app, s.cookie, 'post', `/interviews/${id}/complete`, { version: 2 });
  generateContent.mockRejectedValueOnce(new ApiError({ status: 429, message: 'fixture quota exhausted' }));
  expect((await studentCall(app, s.cookie, 'post', `/interviews/${id}/feedback`, {})).status).toBe(503);
  expect(await InterviewFeedback.countDocuments()).toBe(0); expect((await InterviewSession.findById(id))?.feedbackToken).toBeUndefined();
});
it('requires per-request resume consent, Student ownership, role, CSRF and valid origin before calling Gemini', async () => {
  const { app, generateContent } = configured(); const s = await studentAccount(), other = await studentAccount(), admin = await studentAccount('admin');
  const resume = await Resume.create({ ...resumeFixture(), studentId: s.user._id });
  const path = `/resumes/${resume.id}/ai-suggestions`; const body = { consent: true, jobDescription: 'React developer requirements: TypeScript, testing, Node.js and MongoDB.' };
  expect((await studentCall(app, s.cookie, 'post', path, { jobDescription: body.jobDescription })).status).toBe(400);
  expect((await studentCall(app, s.cookie, 'post', path, { ...body, consent: false })).status).toBe(400);
  expect((await studentCall(app, s.cookie, 'post', path, { ...body, GEMINI_KEY_SELECTION: 'backup' })).status).toBe(400);
  expect((await studentCall(app, other.cookie, 'post', path, body)).status).toBe(404);
  expect((await studentCall(app, admin.cookie, 'post', path, body)).status).toBe(403);
  expect((await request(app).post('/api/v1/student'+path).set('X-Disha360-Request','1').send(body)).status).toBe(401);
  expect((await request(app).post('/api/v1/student'+path).set('Cookie',s.cookie).send(body)).status).toBe(403);
  expect((await request(app).post('/api/v1/student'+path).set('Cookie',s.cookie).set('X-Disha360-Request','1').set('Origin','https://evil.example').send(body)).status).toBe(403);
  expect(generateContent).not.toHaveBeenCalled();
});
it('minimizes and redacts resume data without changing the saved resume or deterministic ATS score', async () => {
  const { app, generateContent } = configured(); const s = await studentAccount();
  const fixture = resumeFixture(); fixture.content.personal.summary += ' Contact Test Student at student@example.test, 1234567890 or https://private.test.';
  const resume = await Resume.create({ ...fixture, studentId: s.user._id });
  const jobDescription = 'React TypeScript web developer: testing, Node.js and MongoDB. Contact student@example.test.';
  const scoreBefore = analyzeResume(fixture.content, jobDescription);
  generateContent.mockResolvedValue(geminiResponse(geminiSuggestion));
  const result = await studentCall(app, s.cookie, 'post', `/resumes/${resume.id}/ai-suggestions`, { consent: true, jobDescription });
  expect(result.status).toBe(200); expect(result.body.data.provider).toBe('Google Gemini'); expect(result.body.data.disclaimer).toContain('No changes');
  const sent = generateContent.mock.calls[0][0].contents;
  for (const privateText of ['Test Student', 'student@example.test', '1234567890', 'https://private.test', 'Delhi', 'College', resume.id, s.user.id, 'Placement application']) expect(sent).not.toContain(privateText);
  expect(sent).toContain('[redacted]'); expect(sent).toContain('TypeScript');
  expect((await Resume.findById(resume.id))?.content).toEqual(fixture.content);
  expect((await Resume.findById(resume.id))?.version).toBe(1);
  expect(analyzeResume(fixture.content, jobDescription)).toEqual(scoreBefore);
  expect(await ResumeAnalysis.countDocuments()).toBe(0);
  generateContent.mockResolvedValueOnce(geminiResponse({ score: 100 }));
  expect((await studentCall(app, s.cookie, 'post', `/resumes/${resume.id}/ai-suggestions`, { consent: true, jobDescription })).status).toBe(503);
});
